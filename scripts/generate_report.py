"""Generate the consolidated findings report (``docs/report.md``).

Builds one synthesis of every analysis from the committed, de-identified result
bundles in ``dashboard/data/``. Every number is read from those executed results;
nothing is typed in by hand. The output is deterministic (no timestamp), so
``tests/test_report.py`` can check that the committed report matches the data.

Usage:
    uv run python scripts/generate_report.py            # write docs/report.md
    uv run python scripts/generate_report.py --check    # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DATA = Path("dashboard/data")
REPORT = Path("docs/report.md")
EXTERNAL = ("ds002778", "ds004584", "ds003490")


def _load(name: str) -> dict:
    return json.loads((DATA / name).read_text())


def _ci(m: dict, nd: int = 3) -> str:
    return f"{m['point']:.{nd}f} [{m['lo']:.{nd}f}, {m['hi']:.{nd}f}]"


def _yn(ok: bool) -> str:
    return "yes" if ok else "no"


def _yes(ok: bool, yes: str = "met", no: str = "not met") -> str:
    return f"**{yes}**" if ok else f"**{no}**"


def build() -> str:
    cohorts = _load("cohorts.json")
    metrics = _load("metrics.json")
    conf = {c: _load(f"confirmatory_{c}.json") for c in ("ds004584", "ds003490")}
    combat = _load("combat.json")
    aperiodic = _load("aperiodic_specparam.json")
    multisite = _load("multisite.json")
    clinical = _load("clinical.json")

    internal = metrics["internal_ds007526"]["results"]
    shift = metrics["dataset_shift"]["results"]["logreg"]["roc_auc"]

    L: list[str] = [
        "# NeuroPD — Consolidated Findings Report",
        "",
        "> Generated by `scripts/generate_report.py` from the committed, de-identified "
        "result bundles in `dashboard/data/`. Every number below is read from executed "
        "results. Regenerate after any analysis changes. Research tool only: nothing "
        "here is a diagnostic or prognostic claim.",
        "",
        "## Question",
        "",
        "Do interpretable resting-state EEG features that separate Parkinson's disease "
        "(PD) from controls in one cohort still work in independent cohorts? And where "
        "they do not, why not?",
        "",
        "## Cohorts (after quality control)",
        "",
        "| cohort | role | n | PD / control | mean age | % male |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for acc, c in cohorts.items():
        L.append(
            f"| {acc} | {c['role']} | {c['n_participants']} | {c['n_pd']} / {c['n_hc']} "
            f"| {c['age_mean']:.1f} | {c['pct_male']:.0f}% |"
        )

    # 1. Site dominates
    ident = {
        "ds002778": shift,
        "ds004584": conf["ds004584"]["dataset_identity"]["logreg"]["roc_auc"],
        "ds003490": conf["ds003490"]["dataset_identity"]["logreg"]["roc_auc"],
    }
    L += [
        "",
        "## Finding 1 — Site is far more predictable than disease",
        "",
        "A logistic regression on the same EEG features tells which dataset a "
        "participant came from (ds007526 vs each other cohort, grouped CV) with ROC-AUC "
        + ", ".join(f"{v:.3f} ({c})" for c, v in ident.items())
        + f". Within ds007526, disease is predicted at ROC-AUC "
        f"{internal['logreg']['roc_auc']['point']:.3f} (logreg, grouped CV) and "
        f"age/sex alone reach {internal['demographics']['roc_auc']['point']:.3f}. "
        "Site and acquisition dominate the shared feature space. (The ds002778 identity "
        "value and the within-ds007526 values come from the v0.1.0 analyses on the "
        "original 210-feature matrix; the others use the current 230 features.)",
        "",
        "## Finding 2 — Disease signal transfers to some sites, not all",
        "",
        "All-feature logistic regression trained on ds007526 only, evaluated once on "
        "each external cohort (ROC-AUC, 95% participant bootstrap CI):",
        "",
        "| external cohort | n (PD) | all-feature logreg | age/sex only |",
        "| --- | --- | --- | --- |",
    ]
    ext_demo = {
        "ds002778": metrics["external_a_to_b"]["results"]["demographics"]["external"]["roc_auc"],
        "ds004584": conf["ds004584"]["baselines"]["demographics"]["external"]["roc_auc"],
        "ds003490": conf["ds003490"]["baselines"]["demographics"]["external"]["roc_auc"],
    }
    for c in EXTERNAL:
        e = combat["cohorts"][c]
        L.append(
            f"| {c} | {e['n_test']} ({e['n_test_pd']}) "
            f"| {_ci(e['methods']['none']['models']['logreg']['roc_auc'])} "
            f"| {_ci(ext_demo[c])} |"
        )
    L += [
        "",
        "Transfer is clear for the largest new site, modest for ds002778 and not "
        "detectable for ds003490 (small, ~1 min of eyes-open EEG). Age/sex alone do not "
        "transfer anywhere, so the transferred signal is not a demographic proxy.",
        "",
        "## Pre-registered and pre-declared tests",
        "",
        "Each test below was written down and committed before its result was computed.",
        "",
        "| ADR | test | result | verdict |",
        "| --- | --- | --- | --- |",
    ]
    for c, p in conf.items():
        auc = p["primary"]["external"]["roc_auc"]
        L.append(
            f"| 0013 | relative-power logreg beats chance on {c} (CI lower bound > 0.5) "
            f"| AUC {_ci(auc)} | {_yes(p['primary']['confirmed'], 'confirmed', 'not confirmed')} |"
        )
    cb = combat["criterion"]
    L.append(
        "| 0014 | ComBat beats no harmonization in all three external cohorts "
        f"| better everywhere? ComBat {_yn(cb['combat'])}, "
        f"ComBat (age/sex) {_yn(cb['combat_agesex'])} "
        f"| {_yes(cb['combat'] or cb['combat_agesex'])} |"
    )
    L.append(
        "| 0015 | peak-separated aperiodic fit beats log-log fit for transfer in all three "
        f"| better everywhere? {_yn(aperiodic['criterion_sp_helps_transfer'])} "
        f"| {_yes(aperiodic['criterion_sp_helps_transfer'])} |"
    )
    L.append(
        "| 0016 | multi-site training beats single-site at all three comparable sites "
        f"| better everywhere? pooled {_yn(multisite['criterion']['B_beats_A_all'])}, "
        f"per-site z {_yn(multisite['criterion']['C_beats_A_all'])} "
        f"| {_yes(multisite['h2_supported'], 'supported', 'not supported')} |"
    )
    for m, v in clinical["primary"].items():
        a, b = v["cohorts"]["ds007526"], v["cohorts"]["ds004584"]
        L.append(
            f"| 0017 | within PD, {m} vs MoCA replicates at both sites "
            f"| r {a['r']:+.3f} (p={a['p']:.3f}) / {b['r']:+.3f} (p={b['p']:.3f}) "
            f"| {_yes(v['replicated'], 'replicated', 'not replicated')} |"
        )

    # Multisite detail
    L += [
        "",
        "## Finding 3 — Harmonization alone does not fix transfer; site diversity may",
        "",
        "Per-feature harmonization (per-cohort z-scoring, ComBat) removes site offsets "
        "but leaves single-site transfer essentially unchanged. Training on three sites "
        "and testing on the fourth (all-feature logreg, ROC-AUC):",
        "",
        "| held-out site | ds007526 only | 3 sites pooled | 3 sites, per-site z |",
        "| --- | --- | --- | --- |",
    ]
    for site, f in multisite["folds"].items():
        cells = [
            _ci(f["arms"][a]["logreg"]["roc_auc"]) if a in f["arms"] else "-"
            for a in ("A", "B", "C")
        ]
        L.append(f"| {site} | " + " | ".join(cells) + " |")
    L += [
        "",
        "Per-site standardization combined with multi-site training tends to help the "
        "two small sites. This is directional (overlapping CIs), and the pre-declared "
        "all-sites criterion was not met.",
        "",
        "## Finding 4 — Within PD, EEG slowing tracks cognition at two sites",
        "",
    ]
    tar = clinical["primary"]["global theta/alpha ratio"]["cohorts"]
    L += [
        "Among PD participants only, a global theta/alpha ratio relates to lower MoCA "
        f"after accounting for age: r = {tar['ds007526']['r']:+.3f} (ds007526, "
        f"n={tar['ds007526']['n']}) and r = {tar['ds004584']['r']:+.3f} (ds004584, "
        f"n={tar['ds004584']['n']}). This is a modest but replicated within-disease "
        "association. Occipital peak alpha frequency shows none.",
        "",
        "## Finding 5 — The 1/f slope effect is partly peak contamination",
        "",
        "PD-minus-control Cohen's d for the aperiodic exponent, plain log-log fit vs "
        "peak-separated spectral parameterization:",
        "",
        "| cohort | log-log | spectral parameterization |",
        "| --- | --- | --- |",
    ]
    for c, e in aperiodic["group_effect"].items():
        L.append(
            f"| {c} | {_ci(e['log-log (ADR 0012)'], 2)} "
            f"| {_ci(e['spectral parameterization'], 2)} |"
        )
    L += [
        "",
        "## What did not hold up",
        "",
        "- The exploratory claim that only *normalized* (relative) band power transfers "
        "(ADR 0010, from ds002778 with n=30) was not supported on ds004584, where every "
        "feature family transferred about equally.",
        "- No harmonization method tested improved transfer consistently across sites.",
        "",
        "## Main limitations",
        "",
        "- Small external cohorts (n=30 and n=33) give wide intervals.",
        "- ds007526 is imbalanced (about 4:1 PD:control) with an age/sex confound, and "
        "quality-control exclusions there are PD-concentrated.",
        "- ds003490 has only about 1 minute of eyes-open EEG per session; its "
        "quality-control losses hit controls hardest.",
        "- The ds004584 motor scale is undocumented, so motor-severity results are "
        "descriptive only.",
        "- ds004584 and ds003490 share an author, so they are not fully independent.",
        "- Full list: `docs/limitations.md`.",
        "",
        "## Where each result lives",
        "",
        "Confirmatory transfer: `docs/confirmatory_transfer.md` (ADR 0013). ComBat: "
        "`docs/combat.md` (ADR 0014). Aperiodic: `docs/aperiodic_specparam.md` (ADR 0015). "
        "Multi-site: `docs/multisite.md` (ADR 0016). Clinical severity: `docs/clinical.md` "
        "(ADR 0017). Audit: `docs/audit.md`.",
        "",
    ]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="NeuroPD consolidated report")
    parser.add_argument("--check", action="store_true", help="Fail if docs/report.md is stale.")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        if not REPORT.is_file() or REPORT.read_text() != text:
            sys.stderr.write("docs/report.md is stale; run scripts/generate_report.py\n")
            return 1
        return 0
    REPORT.write_text(text)
    print(f"Wrote {REPORT}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
