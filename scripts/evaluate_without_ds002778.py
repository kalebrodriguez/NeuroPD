"""Do the classification conclusions depend on ds002778? (pre-declared, ADR 0019).

1. Re-runs leave-one-site-out training (ADR 0016) on ds007526, ds004584 and
   ds003490 only: ds002778 is removed from training as well as testing.
2. Re-applies the ADR 0014 ComBat criterion to ds004584 and ds003490, from the
   committed ``combat.json`` (each pair was fitted without ds002778, so nothing is
   recomputed).
3. Compares site identity with disease transfer for those two cohorts, also from
   ``combat.json``.

Then applies the ADR 0019 rule (a)-(d). Writes
``reports/tables/without_ds002778.json`` (git-ignored) and
``docs/without_ds002778.md``.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

import evaluate_multisite as ms

TABLES_ROOT = Path("reports/tables")
COMMITTED = Path("dashboard/data")
REPORT = Path("docs/without_ds002778.md")
EXCLUDED = "ds002778"
SITES = tuple(s for s in ms.SITES if s != EXCLUDED)
EXTERNAL = tuple(s for s in SITES if s != ms.SINGLE)
PRIMARY = ms.PRIMARY


def _auc(entry: dict, arm: str) -> float:
    return float(entry["arms"][arm][PRIMARY]["roc_auc"]["point"])


def evaluate(loso: dict, loso_original: dict, combat: dict) -> dict:
    """Apply the ADR 0019 rule. Pure function of the three result payloads."""
    none = {c: combat["cohorts"][c]["methods"]["none"] for c in EXTERNAL}
    identity = {
        c: {
            "site_identity_auc": float(none[c]["dataset_identity_auc"]),
            "disease_transfer_auc": float(none[c]["models"][PRIMARY]["roc_auc"]["point"]),
        }
        for c in EXTERNAL
    }
    combat_crit = {
        m: all(
            combat["cohorts"][c]["methods"][m]["models"][PRIMARY]["roc_auc"]["point"]
            > none[c]["models"][PRIMARY]["roc_auc"]["point"]
            for c in EXTERNAL
        )
        for m in ("combat", "combat_agesex")
    }
    folds = loso["folds"]
    rule = {
        "a_identity_exceeds_transfer": all(
            v["site_identity_auc"] > v["disease_transfer_auc"] for v in identity.values()
        ),
        "b_combat_still_not_met": not any(combat_crit.values()),
        "c_h2_still_not_supported": not loso["h2_supported"],
        "d_c_beats_a_at_ds003490": _auc(folds["ds003490"], "C") > _auc(folds["ds003490"], "A"),
    }
    comparison = {
        site: {
            arm: {
                "with_ds002778": _auc(loso_original["folds"][site], arm),
                "without_ds002778": _auc(folds[site], arm),
            }
            for arm in folds[site]["arms"]
        }
        for site in SITES
    }
    return {
        "identity_vs_transfer": identity,
        "combat_criterion": combat_crit,
        "rule": rule,
        "unchanged": all(rule.values()),
        "loso_comparison": comparison,
    }


def run(log) -> dict:
    loso = ms.run(log, sites_used=SITES, adr="0019")
    loso_original = json.loads((COMMITTED / "multisite.json").read_text())
    combat = json.loads((COMMITTED / "combat.json").read_text())
    out = {
        "adr": "0019",
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "excluded": EXCLUDED,
        "sites": list(SITES),
        "loso": loso,
        **evaluate(loso, loso_original, combat),
    }
    log.info("ADR 0019 rule: %s -> unchanged=%s", out["rule"], out["unchanged"])
    return out


def _ci(m: dict) -> str:
    return f"{m['point']:.3f} [{m['lo']:.3f}, {m['hi']:.3f}]"


def _yes(b: bool) -> str:
    return "yes" if b else "**no**"


def render(p: dict) -> str:
    rule, loso = p["rule"], p["loso"]
    lines = [
        "# Classification Conclusions Without ds002778 (pre-declared, ADR 0019)",
        "",
        f"> Generated by `scripts/evaluate_without_ds002778.py` on {p['generated_utc']}. "
        "The ds002778 authors advise against PD-vs-control classification on their "
        "dataset. This re-runs leave-one-site-out training (ADR 0016) on "
        f"{', '.join(p['sites'])} only, and re-applies the ComBat criterion (ADR 0014) "
        "to the two remaining external cohorts. Intervals are 95% participant-level "
        "bootstrap CIs.",
        "",
        "## Pre-declared rule",
        "",
        "| check | holds without ds002778 |",
        "| --- | --- |",
        "| (a) site identity AUC > disease transfer AUC in each remaining cohort | "
        f"{_yes(rule['a_identity_exceeds_transfer'])} |",
        "| (b) ComBat criterion still not met (either variant) | "
        f"{_yes(rule['b_combat_still_not_met'])} |",
        "| (c) H2 (multi-site beats single-site everywhere) still not supported | "
        f"{_yes(rule['c_h2_still_not_supported'])} |",
        f"| (d) directional: arm C > arm A at ds003490 | {_yes(rule['d_c_beats_a_at_ds003490'])} |",
        "",
        "Verdict: classification conclusions are **"
        + ("unchanged" if p["unchanged"] else "changed (see the rows marked no)")
        + "** without ds002778.",
        "",
        "## Leave-one-site-out, all-feature logreg external ROC-AUC",
        "",
        "Sites (n, PD fraction): "
        + ", ".join(
            f"{s} ({loso['n_by_site'][s]}, {loso['pd_fraction_by_site'][s]:.0%})"
            for s in loso["n_by_site"]
        )
        + ".",
        "",
        "| held-out site | n (PD) | A single-site | B multi-site pooled "
        "| C multi-site per-site z |",
        "| --- | --- | --- | --- | --- |",
    ]
    for s, f in loso["folds"].items():
        cells = [_ci(f["arms"][a][PRIMARY]["roc_auc"]) if a in f["arms"] else "-" for a in ms.ARMS]
        lines.append(f"| {s} | {f['n_test']} ({f['n_test_pd']}) | " + " | ".join(cells) + " |")
    lines += [
        "",
        "### Point estimates with and without ds002778 in training",
        "",
        "| held-out site | arm | with ds002778 (ADR 0016) | without (ADR 0019) |",
        "| --- | --- | --- | --- |",
    ]
    for site, arms in p["loso_comparison"].items():
        for arm, v in arms.items():
            lines.append(
                f"| {site} | {arm} | {v['with_ds002778']:.3f} | {v['without_ds002778']:.3f} |"
            )
    lines += [
        "",
        "## Site identity vs disease transfer (from ADR 0014, trained on ds007526)",
        "",
        "| cohort | site identity AUC | disease transfer AUC |",
        "| --- | --- | --- |",
    ]
    for c, v in p["identity_vs_transfer"].items():
        lines.append(f"| {c} | {v['site_identity_auc']:.3f} | {v['disease_transfer_auc']:.3f} |")
    crit = p["combat_criterion"]
    lines += [
        "",
        "ComBat criterion on ds004584 and ds003490 (beats no harmonization in both): "
        + ", ".join(f"`{m}` {'met' if ok else 'not met'}" for m, ok in crit.items())
        + ".",
        "",
        "Research tool only: group-level estimates, not a diagnostic test. "
        "Interpretation: ADR 0019.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    from neuropd.logging import configure_logging

    log = configure_logging()
    payload = run(log)
    TABLES_ROOT.mkdir(parents=True, exist_ok=True)
    (TABLES_ROOT / "without_ds002778.json").write_text(json.dumps(payload, indent=2))
    REPORT.write_text(render(payload))
    print(f"Wrote {REPORT}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
