"""Pre-declared robustness checks for the theta/alpha-MoCA association (ADR 0018).

Reuses the ADR 0017 participants, features and statistic (PD after QC with MoCA;
Spearman partial correlation, two-sided t-test p, bootstrap CI) and adds:
age+sex, age+sex+motor, MAD-based outlier exclusion, a theta/alpha decomposition,
per-region topography and a fixed-effect Fisher-z pooled estimate.

Writes ``reports/tables/clinical_robustness.json`` (git-ignored) and
``docs/clinical_robustness.md``.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

from evaluate_clinical import COHORTS, REGIONS, load
from neuropd.data.demographics import load_demographics
from neuropd.evaluation.clinical import partial_spearman

TABLES_ROOT = Path("reports/tables")
REPORT = Path("docs/clinical_robustness.md")
MARKER = "global theta/alpha ratio"
SEED, N_BOOT, ALPHA = 20240517, 2000, 0.05


def _pc(frame: pd.DataFrame, feature: str, covars: list[str]) -> dict:
    res = partial_spearman(
        frame[feature].to_numpy(),
        frame["moca"].to_numpy(),
        frame[covars].to_numpy(),
        n_boot=N_BOOT,
        seed=SEED,
    )
    return {"r": res.r, "p": res.p, "n": res.n, "lo": res.lo, "hi": res.hi}


def _with_sex(cohort: str) -> pd.DataFrame:
    d = load(cohort)
    d["sex_male"] = load_demographics(cohort, list(d["participant_id"]))[:, 1]
    d["global rel theta"] = d[[f"rel_power_theta__{r}__median" for r in REGIONS]].mean(axis=1)
    d["global rel alpha"] = d[[f"rel_power_alpha__{r}__median" for r in REGIONS]].mean(axis=1)
    return d


def _drop_outliers(d: pd.DataFrame) -> pd.DataFrame:
    x = d[MARKER]
    med = x.median()
    mad = 1.4826 * (x - med).abs().median()
    return d[(x - med).abs() <= 3 * mad] if mad > 0 else d


def fisher_pool(rs: list[float], ns: list[int]) -> dict:
    """Fixed-effect Fisher-z pooled correlation with 95% CI (weights n - 3)."""
    z = np.arctanh(np.asarray(rs))
    w = np.asarray(ns, dtype=float) - 3
    zp = float(np.sum(w * z) / np.sum(w))
    se = float(1 / np.sqrt(np.sum(w)))
    p = float(2 * stats.norm.sf(abs(zp / se)))
    return {
        "r": float(np.tanh(zp)),
        "lo": float(np.tanh(zp - 1.96 * se)),
        "hi": float(np.tanh(zp + 1.96 * se)),
        "p": p,
    }


def run(log) -> dict:
    data = {c: _with_sex(c) for c in COHORTS}
    checks = {
        "1 age + sex": (lambda d: d, ["age", "sex_male"]),
        "2 age + sex + motor": (lambda d: d, ["age", "sex_male", "motor"]),
        "3 outliers removed (age)": (_drop_outliers, ["age"]),
    }
    out: dict = {
        "adr": "0018",
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "checks": {},
    }
    for name, (sel, cov) in checks.items():
        out["checks"][name] = {c: _pc(sel(d), MARKER, cov) for c, d in data.items()}
        log.info(
            "%s: %s",
            name,
            ", ".join(
                f"{c} r={v['r']:+.3f} p={v['p']:.4f} n={v['n']}"
                for c, v in out["checks"][name].items()
            ),
        )
    out["robust"] = all(
        v["r"] < 0 and v["p"] < ALPHA for res in out["checks"].values() for v in res.values()
    )
    out["decomposition"] = {
        f: {c: _pc(d, f, ["age"]) for c, d in data.items()}
        for f in ("global rel theta", "global rel alpha")
    }
    out["topography"] = {
        r: {c: _pc(d, f"theta_alpha_ratio__{r}__median", ["age"]) for c, d in data.items()}
        for r in REGIONS
    }
    base = {c: _pc(d, MARKER, ["age"]) for c, d in data.items()}
    out["pooled_age_only"] = fisher_pool(
        [v["r"] for v in base.values()], [v["n"] for v in base.values()]
    )
    out["base_age_only"] = base
    return out


def _r(v: dict) -> str:
    return f"{v['r']:+.3f} [{v['lo']:+.2f}, {v['hi']:+.2f}], p={v['p']:.4f}, n={v['n']}"


def render(p: dict) -> str:
    L = [
        "# Robustness of the Theta/Alpha-Cognition Association (pre-declared, ADR 0018)",
        "",
        f"> Generated by `scripts/evaluate_clinical_robustness.py` on {p['generated_utc']}. "
        "PD participants after QC with a MoCA score (as in ADR 0017). Spearman partial "
        "correlation of the global theta/alpha ratio with MoCA, two-sided t-test p, 95% "
        "bootstrap CI.",
        "",
        "## Pre-declared checks",
        "",
        "| check (covariates) | ds007526 | ds004584 |",
        "| --- | --- | --- |",
        f"| ADR 0017 reference (age) | {_r(p['base_age_only']['ds007526'])} "
        f"| {_r(p['base_age_only']['ds004584'])} |",
    ]
    for name, v in p["checks"].items():
        L.append(f"| {name} | {_r(v['ds007526'])} | {_r(v['ds004584'])} |")
    L += [
        "",
        "Pre-declared criterion (negative sign and p < 0.05 at both sites under checks "
        f"1-3): **{'robust' if p['robust'] else 'not robust'}**.",
        "",
        "## Descriptive: which side of the ratio carries it (age-partialled)",
        "",
        "| feature | ds007526 | ds004584 |",
        "| --- | --- | --- |",
    ]
    for f, v in p["decomposition"].items():
        L.append(f"| {f} | {_r(v['ds007526'])} | {_r(v['ds004584'])} |")
    L += [
        "",
        "## Descriptive: topography (theta/alpha ratio per region, age-partialled)",
        "",
        "| region | ds007526 | ds004584 |",
        "| --- | --- | --- |",
    ]
    for reg, v in p["topography"].items():
        L.append(f"| {reg} | {_r(v['ds007526'])} | {_r(v['ds004584'])} |")
    po = p["pooled_age_only"]
    L += [
        "",
        "## Descriptive: pooled estimate",
        "",
        f"Fixed-effect Fisher-z pooled partial r (age) = **{po['r']:+.3f}** "
        f"[{po['lo']:+.3f}, {po['hi']:+.3f}], p = {po['p']:.5f}.",
        "",
        "Observational association in research data. Not diagnostic or prognostic. "
        "Interpretation: ADR 0018.",
        "",
    ]
    return "\n".join(L)


def main() -> int:
    from neuropd.logging import configure_logging

    log = configure_logging()
    payload = run(log)
    TABLES_ROOT.mkdir(parents=True, exist_ok=True)
    (TABLES_ROOT / "clinical_robustness.json").write_text(json.dumps(payload, indent=2))
    REPORT.write_text(render(payload))
    print(f"Wrote {REPORT}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
