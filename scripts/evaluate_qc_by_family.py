"""Is the QC sensitivity of transfer carried by amplitude-sensitive features? (ADR 0021).

For each feature family and each ADR 0020 arm (150 / 200 / 400 µV), fits logreg on
ds007526 and evaluates it once on each external cohort, exactly as ADR 0020 does for
all features. Degradation = mean over cohorts of AUC(150) - AUC(400). H5: every
amplitude-sensitive family degrades more than every amplitude-invariant family.

Writes ``reports/tables/qc_by_family.json`` (git-ignored) and ``docs/qc_by_family.md``.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path

from evaluate_combat import _identity_auc
from evaluate_qc_threshold import ARMS, DEV, EXTERNAL, PRIMARY_ARM, _features, _transfer
from neuropd.features.families import FAMILIES, family_columns
from neuropd.features.matrix import feature_columns

AMPLITUDE_SENSITIVE = ("absolute power", "log power")
AMPLITUDE_INVARIANT = ("relative power", "slowing (paf/sef/ratios)")
LOOSEST = "400"
TABLES_ROOT = Path("reports/tables")
REPORT = Path("docs/qc_by_family.md")


def degradation(auc: dict, family: str) -> float:
    """Mean over external cohorts of AUC(primary) - AUC(loosest) for one family."""
    per = [
        auc[PRIMARY_ARM][family][c]["point"] - auc[LOOSEST][family][c]["point"] for c in EXTERNAL
    ]
    return float(sum(per) / len(per))


def apply_rule(auc: dict) -> dict:
    deg = {f: degradation(auc, f) for f in FAMILIES}
    lo_sensitive = min(deg[f] for f in AMPLITUDE_SENSITIVE)
    hi_invariant = max(deg[f] for f in AMPLITUDE_INVARIANT)
    return {
        "degradation": deg,
        "min_sensitive": lo_sensitive,
        "max_invariant": hi_invariant,
        "h5_supported": bool(lo_sensitive > hi_invariant),
    }


def run(log) -> dict:
    auc: dict = {}
    identity: dict = {}
    for arm, root in ARMS.items():
        frames = {c: _features(root, c) for c in (DEV, *EXTERNAL)}
        cols = feature_columns(frames[DEV])
        auc[arm] = {}
        if arm in (PRIMARY_ARM, LOOSEST):
            identity[arm] = {}
        for fam in FAMILIES:
            fcols = family_columns(cols, fam)
            auc[arm][fam] = {c: _transfer(frames[DEV], frames[c], fcols, c) for c in EXTERNAL}
            if arm in (PRIMARY_ARM, LOOSEST):
                identity[arm][fam] = {
                    c: _identity_auc(
                        frames[DEV][fcols].to_numpy(dtype=float),
                        frames[c][fcols].to_numpy(dtype=float),
                        frames[DEV]["participant_id"].to_numpy(),
                        frames[c]["participant_id"].to_numpy(),
                        c,
                    )
                    for c in EXTERNAL
                }
            log.info(
                "%s µV %-26s %s",
                arm,
                fam,
                " ".join(f"{c}={auc[arm][fam][c]['point']:.3f}" for c in EXTERNAL),
            )
    out = {
        "adr": "0021",
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "auc": auc,
        "identity": identity,
        **apply_rule(auc),
    }
    log.info("ADR 0021: degradation %s -> H5 %s", out["degradation"], out["h5_supported"])
    return out


def render(p: dict) -> str:
    arms = list(p["auc"])
    lines = [
        "# QC Sensitivity of Transfer by Feature Family (pre-declared, ADR 0021)",
        "",
        f"> Generated by `scripts/evaluate_qc_by_family.py` on {p['generated_utc']}. "
        "Logistic regression per feature family, trained on ds007526 and evaluated once "
        "on each external cohort, on the ADR 0020 feature matrices (artifact threshold "
        "150 / 200 / 400 µV). Degradation = mean over the three cohorts of "
        "AUC(150 µV) - AUC(400 µV).",
        "",
        "## Pre-declared prediction (H5)",
        "",
        "Every amplitude-sensitive family (absolute, log power) degrades more than every "
        "amplitude-invariant family (relative power, slowing): "
        f"min {p['min_sensitive']:+.3f} vs max {p['max_invariant']:+.3f} → "
        f"**H5 {'supported' if p['h5_supported'] else 'not supported'}**.",
        "",
        "| family | class | degradation |",
        "| --- | --- | --- |",
    ]
    for fam, d in p["degradation"].items():
        cls = (
            "amplitude-sensitive"
            if fam in AMPLITUDE_SENSITIVE
            else "amplitude-invariant"
            if fam in AMPLITUDE_INVARIANT
            else "mixed (descriptive)"
        )
        lines.append(f"| {fam} | {cls} | {d:+.3f} |")
    lines += [
        "",
        "## Transfer ROC-AUC by family and threshold",
        "",
        "| family | cohort | " + " | ".join(f"{a} µV" for a in arms) + " |",
        "| --- | --- |" + " --- |" * len(arms),
    ]
    for fam in p["degradation"]:
        for c in EXTERNAL:
            lines.append(
                f"| {fam} | {c} | "
                + " | ".join(f"{p['auc'][a][fam][c]['point']:.3f}" for a in arms)
                + " |"
            )
    id_arms = list(p["identity"])
    lines += [
        "",
        "## Site identity AUC by family (ds007526 vs cohort; descriptive)",
        "",
        "| family | cohort | " + " | ".join(f"{a} µV" for a in id_arms) + " |",
        "| --- | --- |" + " --- |" * len(id_arms),
    ]
    for fam in p["degradation"]:
        for c in EXTERNAL:
            lines.append(
                f"| {fam} | {c} | "
                + " | ".join(f"{p['identity'][a][fam][c]:.3f}" for a in id_arms)
                + " |"
            )
    lines += [
        "",
        "Research tool only: group-level estimates, not a diagnostic test. "
        "Interpretation: ADR 0021.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    from neuropd.logging import configure_logging

    log = configure_logging()
    payload = run(log)
    TABLES_ROOT.mkdir(parents=True, exist_ok=True)
    (TABLES_ROOT / "qc_by_family.json").write_text(json.dumps(payload, indent=2))
    REPORT.write_text(render(payload))
    print(f"Wrote {REPORT}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
