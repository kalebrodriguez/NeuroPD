"""Generate a paper-style manuscript draft (``docs/manuscript.md``).

Every number is read from the committed, de-identified result bundles in
``dashboard/data/``; the prose is fixed text. The only references cited are those
already verified and listed in ``CITATION.cff`` (dataset DOIs and three method
papers), so the draft makes no unsourced claims about the wider literature.
Deterministic output; ``tests/test_manuscript.py`` fails if the committed draft is
stale.

Usage:
    uv run python scripts/generate_manuscript.py            # write the draft
    uv run python scripts/generate_manuscript.py --check    # exit 1 if stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DATA = Path("dashboard/data")
OUT = Path("docs/manuscript.md")
EXTERNAL = ("ds002778", "ds004584", "ds003490")


def _load(name: str) -> dict:
    return json.loads((DATA / name).read_text())


def _ci(m: dict, nd: int = 2) -> str:
    return f"{m['point']:.{nd}f} [95% CI {m['lo']:.{nd}f}-{m['hi']:.{nd}f}]"


def build() -> str:
    cohorts = _load("cohorts.json")
    metrics = _load("metrics.json")
    conf = {c: _load(f"confirmatory_{c}.json") for c in ("ds004584", "ds003490")}
    combat = _load("combat.json")
    ap = _load("aperiodic_specparam.json")
    ms = _load("multisite.json")
    cl = _load("clinical.json")
    rb = _load("clinical_robustness.json")
    rb_out = rb["checks"]["3 outliers removed (age)"]

    n_total = sum(c["n_participants"] for c in cohorts.values())
    n_pd = sum(c["n_pd"] for c in cohorts.values())
    none = {
        c: combat["cohorts"][c]["methods"]["none"]["models"]["logreg"]["roc_auc"] for c in EXTERNAL
    }
    ident = {
        "ds002778": metrics["dataset_shift"]["results"]["logreg"]["roc_auc"],
        "ds004584": conf["ds004584"]["dataset_identity"]["logreg"]["roc_auc"],
        "ds003490": conf["ds003490"]["dataset_identity"]["logreg"]["roc_auc"],
    }
    internal = metrics["internal_ds007526"]["results"]
    h1 = {c: p["primary"]["external"]["roc_auc"] for c, p in conf.items()}
    tar = cl["primary"]["global theta/alpha ratio"]["cohorts"]
    paf = cl["primary"]["occipital PAF"]["cohorts"]
    msf = ms["folds"]
    ge = ap["group_effect"]

    L = [
        "# Cross-site generalization of interpretable resting-state EEG markers of "
        "Parkinson's disease: a pre-registered multi-cohort study",
        "",
        "*Draft manuscript generated by `scripts/generate_manuscript.py` from the "
        "project's executed results. Research tool only; nothing here is a diagnostic "
        "or prognostic claim. Author: Kaleb Rodriguez. Status: draft for owner review.*",
        "",
        "## Abstract",
        "",
        "**Background.** Resting-state EEG features often separate people with "
        "Parkinson's disease (PD) from controls within one dataset. Whether they "
        "generalize across independent sites needs to be tested with an analysis fixed "
        "in advance.",
        "",
        f"**Methods.** We analysed {n_total} participants ({n_pd} PD) from four public "
        "OpenNeuro cohorts with one frozen pipeline (31 shared channels, interpretable "
        "region-level spectral and complexity features). A model trained on one cohort "
        "(ds007526) was evaluated once on each other cohort. Two new cohorts were tested "
        "under a pre-registered plan, and four further analyses were declared before "
        "their results: ComBat harmonization, a peak-separated aperiodic fit, "
        "leave-one-site-out training, and a within-PD clinical severity replication.",
        "",
        f"**Results.** Site was far more predictable than disease: classifiers "
        f"identified the cohort of origin with ROC-AUC {min(ident.values()):.2f}-"
        f"{max(ident.values()):.2f}. Disease transfer was uneven: "
        + "; ".join(f"{c} {_ci(none[c])}" for c in EXTERNAL)
        + ". The pre-registered relative-power test passed on ds004584 "
        f"({_ci(h1['ds004584'])}) but not on the smaller ds003490 "
        f"({_ci(h1['ds003490'])}). Harmonization did not improve transfer consistently. "
        "Within PD, a global theta/alpha ratio was associated with lower cognitive "
        f"scores (MoCA) at both sites with severity data (age-partialled Spearman "
        f"r = {tar['ds007526']['r']:.2f} and {tar['ds004584']['r']:.2f}, both p < 0.025).",
        "",
        "**Conclusions.** Interpretable EEG features carry disease-related information "
        "that transfers to some independent sites but not reliably to all, and site "
        "effects dominate the feature space. A slowing index tracked cognition within PD "
        "at two sites, a modest but replicated within-disease association.",
        "",
        "## 1. Introduction",
        "",
        "Group differences or classifiers developed within a single EEG cohort can "
        "reflect site-specific acquisition, population and demographic structure rather "
        "than disease. This "
        "study asks a narrower question: do interpretable resting-state features that "
        "separate PD from controls in one cohort still do so in independent cohorts, and "
        "where they do not, why? We emphasise pre-specified tests, participant-level "
        "uncertainty and reporting of negative results.",
        "",
        "## 2. Methods",
        "",
        "### 2.1 Cohorts",
        "",
        "Four public CC0 datasets from OpenNeuro were used (counts after quality control):",
        "",
        "| cohort | role | n | PD / control | mean age | % male |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for acc, c in cohorts.items():
        L.append(
            f"| {acc} | {c['role']} | {c['n_participants']} | {c['n_pd']} / {c['n_hc']} "
            f"| {c['age_mean']:.1f} | {c['pct_male']:.0f}% |"
        )
    L += [
        "",
        "All recordings are eyes-open rest. For ds003490 only the eyes-open block of a "
        "longer recording was analysed.",
        "",
        "### 2.2 Preprocessing and features",
        "",
        "One pipeline was applied to all cohorts:",
        "",
        "- the 31 shared 10-20 channels;",
        "- per-cohort mains notch, 1-40 Hz band-pass, resampling to 250 Hz;",
        "- average reference and 2 s epochs with amplitude-based rejection;",
        "- recordings with fewer than 20 clean epochs were excluded.",
        "",
        "Features were relative, absolute and log band power, slowing indices, "
        "complexity measures and an aperiodic (1/f) fit. They were averaged within five "
        "scalp regions and summarised per participant by the median and IQR over epochs "
        "(230 features).",
        "",
        "Cohort-specific adapters restored an unstored reference channel and "
        "interpolated two channels absent in one cohort. Each adapter was decided from "
        "metadata before any results and is recorded in the decision log.",
        "",
        "### 2.3 Evaluation",
        "",
        "Models were the project's fixed baselines: regularized logistic regression, "
        "linear SVM, random forest, and an age/sex-only model. Within-cohort "
        "performance used participant-grouped repeated cross-validation. External "
        "evaluation fitted a model on all of ds007526 and evaluated it once on each "
        "other cohort, with nothing tuned on the external data. Intervals are 95% "
        "participant-level bootstrap CIs.",
        "",
        "Pre-specified analyses, each fixed in a decision record before its result:",
        "",
        "1. **Confirmatory transfer** of relative band power to two new cohorts.",
        "2. **ComBat harmonization** (Johnson et al., 2007; Fortin et al., 2018).",
        "3. **A peak-separated aperiodic fit** (Donoghue et al., 2020).",
        "4. **Leave-one-site-out training.**",
        "5. **A within-PD association** of two slowing markers with MoCA, controlling "
        "for age, followed by pre-declared robustness checks.",
        "",
        "## 3. Results",
        "",
        "### 3.1 Site dominates the feature space",
        "",
        "Cohort of origin was predicted with ROC-AUC "
        + ", ".join(f"{v:.2f} ({c} vs ds007526)" for c, v in ident.items())
        + f". Within ds007526 the EEG model reached ROC-AUC "
        f"{internal['logreg']['roc_auc']['point']:.2f} and age/sex alone "
        f"{internal['demographics']['roc_auc']['point']:.2f}.",
        "",
        "### 3.2 Cross-site disease transfer",
        "",
        "All-feature logistic regression trained on ds007526:",
        "",
        "| external cohort | n (PD) | ROC-AUC |",
        "| --- | --- | --- |",
    ]
    for c in EXTERNAL:
        e = combat["cohorts"][c]
        L.append(f"| {c} | {e['n_test']} ({e['n_test_pd']}) | {_ci(none[c])} |")
    L += [
        "",
        "Age/sex-only models were at or below chance on every external cohort.",
        "",
        "In the pre-registered test, relative band power transferred to ds004584 "
        f"({_ci(h1['ds004584'])}) but not detectably to ds003490 ({_ci(h1['ds003490'])}). "
        "On ds004584 every feature family transferred to a similar degree. The earlier "
        "exploratory impression that only normalized features transfer therefore did "
        "not hold.",
        "",
        "### 3.3 Harmonization and multi-site training",
        "",
        "ComBat removed per-feature site differences, so cohort identity was no longer "
        "separable. It did not consistently improve disease transfer: the pre-declared "
        "criterion (better in all three cohorts) was "
        + (
            "met for at least one variant."
            if any(combat["criterion"].values())
            else "not met for either variant, with or without age/sex protected."
        ),
        "",
        "Leave-one-site-out training (all-feature logistic regression):",
        "",
        "| held-out site | trained on ds007526 only | 3 sites pooled | 3 sites, per-site z |",
        "| --- | --- | --- | --- |",
    ]
    for site, f in msf.items():
        cells = [
            f"{f['arms'][a]['logreg']['roc_auc']['point']:.2f}" if a in f["arms"] else "-"
            for a in ("A", "B", "C")
        ]
        L.append(f"| {site} | " + " | ".join(cells) + " |")
    L += [
        "",
        "Multi-site training did not beat single-site training at every site, so the "
        "pre-declared hypothesis was not supported. Per-site standardization with "
        "multi-site training tended to help the two smallest sites; their intervals "
        "overlap.",
        "",
        "### 3.4 Aperiodic activity",
        "",
        "The PD-minus-control difference in the aperiodic exponent (Cohen's d) was "
        "smaller with the peak-separated fit than with a plain log-log fit:",
        "",
    ]
    L += [
        f"- {c}: {e['log-log (ADR 0012)']['point']:.2f} → "
        f"{e['spectral parameterization']['point']:.2f}"
        for c, e in ge.items()
    ]
    L += [
        "",
        "The effect remained clearly non-zero only in ds004584 "
        f"({_ci(ge['ds004584']['spectral parameterization'])}). Part of the plain-fit "
        "effect therefore reflects oscillatory peaks.",
        "",
        "### 3.5 Within-PD association with cognition",
        "",
        "Among PD participants, the global theta/alpha ratio was associated with lower "
        "MoCA after controlling for age:",
        "",
        f"- ds007526: r = {tar['ds007526']['r']:.2f}, p = {tar['ds007526']['p']:.3f}, "
        f"n = {tar['ds007526']['n']}",
        f"- ds004584: r = {tar['ds004584']['r']:.2f}, p = {tar['ds004584']['p']:.3f}, "
        f"n = {tar['ds004584']['n']}",
        "",
        "This met the pre-registered replication criterion. Pre-declared robustness "
        "checks were "
        + ("passed" if rb["robust"] else "not passed")
        + ". The sign stayed negative after adding sex and motor severity, but "
        "excluding extreme ratio values weakened it (r = "
        + f"{rb_out['ds007526']['r']:.2f}, p = {rb_out['ds007526']['p']:.2f}; "
        + f"r = {rb_out['ds004584']['r']:.2f}, p = {rb_out['ds004584']['p']:.2f}). "
        "The association is concentrated in participants with marked slowing and "
        "lower cognition, and is carried mainly by lower relative alpha. Occipital peak alpha "
        f"frequency showed no association (r = {paf['ds007526']['r']:.2f} and "
        f"{paf['ds004584']['r']:.2f}).",
        "",
        "## 4. Discussion",
        "",
        "Three conclusions follow:",
        "",
        "- **Site effects dominate.** Disease-related transfer is real but uneven: clear "
        "for the largest independent cohort, absent for the smallest.",
        "- **Harmonization does not fix this.** Per-feature harmonization, including "
        "ComBat, removed site offsets without fixing transfer. The limiting site "
        "differences are therefore not simple per-feature location and scale shifts. "
        "Training on several sites with per-site standardization is a promising "
        "direction, but it was not confirmed here.",
        "- **A within-disease association replicates, modestly.** The theta/alpha ratio "
        "tracked cognition at two independent sites, even where PD-versus-control "
        "classification was site-dependent. It is driven by a tail of participants "
        "with marked slowing and did not pass the stricter robustness checks.",
        "",
        "Of eight pre-registered or pre-declared tests, two passed. The robustness "
        "check of the within-PD association did not pass. We report all eight.",
        "",
        "### Limitations",
        "",
        "- External cohorts are small (n=30 and n=33), so intervals are wide.",
        "- The development cohort is imbalanced (about 4:1 PD:control), with an age/sex confound.",
        "- Quality-control exclusions were uneven across groups in two cohorts.",
        "- One cohort provides only about 1 minute of eyes-open EEG per session.",
        "- One cohort's motor scale is undocumented, so motor results are descriptive only.",
        "- Two cohorts share an author.",
        "- Associations are observational.",
        "",
        "## Data and code availability",
        "",
        "Data are public on OpenNeuro under CC0:",
        "",
        "- ds007526 (doi:10.18112/openneuro.ds007526.v1.0.2)",
        "- ds002778 (doi:10.18112/openneuro.ds002778.v1.0.5)",
        "- ds004584 (doi:10.18112/openneuro.ds004584.v1.0.0)",
        "- ds003490 (doi:10.18112/openneuro.ds003490.v1.1.0)",
        "",
        "The ds002778 authors ask to be contacted before publication. Code, decision "
        "records and executed results are at "
        "https://github.com/kalebrodriguez/NeuroPD (MIT licence).",
        "",
        "## References",
        "",
        "- Donoghue T, et al. (2020). Parameterizing neural power spectra into periodic "
        "and aperiodic components. *Nature Neuroscience* 23:1655-1665. "
        "doi:10.1038/s41593-020-00744-x",
        "- Fortin J-P, et al. (2018). Harmonization of cortical thickness measurements "
        "across scanners and sites. *NeuroImage* 167:104-120. "
        "doi:10.1016/j.neuroimage.2017.11.024",
        "- Johnson WE, Li C, Rabinovic A (2007). Adjusting batch effects in microarray "
        "expression data using empirical Bayes methods. *Biostatistics* 8:118-127. "
        "doi:10.1093/biostatistics/kxj037",
        "",
    ]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="NeuroPD manuscript draft")
    parser.add_argument("--check", action="store_true", help="Fail if the draft is stale.")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.stderr.write("docs/manuscript.md is stale; run scripts/generate_manuscript.py\n")
            return 1
        return 0
    OUT.write_text(text)
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
